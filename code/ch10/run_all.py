"""Regenerate every number and figure in Chapter 10 by running each of the chapter's scripts.

Usage:  python code/ch10/run_all.py
Scripts: proforma, leverage, cycle, smoothing, reits, timber, storage, inflation, exercises. Each draws
from its own random stream (numbers_ch10.rng_for), so a script run alone reproduces exactly the numbers it
contributes here.
Writes  figures/ch10/*.png, code/ch10/out/*.json, code/ch10/out/numbers.json, chapters/ch10-numbers.tex
"""
import importlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numbers_ch10 as R  # noqa: E402

SCRIPTS = ["proforma", "leverage", "cycle", "smoothing", "reits", "timber", "storage", "inflation",
           "exercises"]


def main(only=None):
    for s in (only or SCRIPTS):
        importlib.import_module(s).main()
        print(f"{s}: done ({len(R.N)} numbers so far)", flush=True)
    (HERE / "out" / "numbers.json").write_text(json.dumps(dict(N=R.N, RAW=R.RAW), indent=1))
    lines = ["% Generated by code/ch10/run_all.py. Do not edit by hand."]
    for k in sorted(R.N):
        assert k.isalpha(), k
        lines.append(f"\\newcommand{{\\{k}}}{{{R.N[k]}}}")
    (R.ROOT / "chapters" / "ch10-numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(R.N)} numbers, figures in {R.ROOT / 'figures' / 'ch10'}")


if __name__ == "__main__":
    main(sys.argv[1:] or None)
