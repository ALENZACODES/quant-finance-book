"""Regenerate every number and figure in Chapter 11 by running each of the chapter's scripts.

Usage:  python code/ch11/run_all.py
Scripts: waterfall, performance, lbo, valuation, discounts, exercises. Each draws from its own random
stream (numbers_ch11.rng_for), so a script run alone reproduces exactly the numbers it contributes
here; discounts.py reads the valuation's output, so valuation.py must have been run before it.
Writes  figures/ch11/*.png, code/ch11/out/*.json, code/ch11/out/numbers.json, chapters/ch11-numbers.tex
"""
import importlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numbers_ch11 as R  # noqa: E402

SCRIPTS = ["waterfall", "performance", "lbo", "valuation", "discounts", "exercises"]


def main(only=None):
    for s in (only or SCRIPTS):
        importlib.import_module(s).main()
        print(f"{s}: done ({len(R.N)} numbers so far)", flush=True)
    (HERE / "out" / "numbers.json").write_text(json.dumps(dict(N=R.N, RAW=R.RAW), indent=1))
    lines = ["% Generated by code/ch11/run_all.py. Do not edit by hand."]
    for k in sorted(R.N):
        assert k.isalpha(), k
        lines.append(f"\\newcommand{{\\{k}}}{{{R.N[k]}}}")
    (R.ROOT / "chapters" / "ch11-numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(R.N)} numbers, figures in {R.ROOT / 'figures' / 'ch11'}")


if __name__ == "__main__":
    main(sys.argv[1:] or None)
