"""Regenerate every number and figure in Chapter 2 by running each of the chapter's scripts.

Usage:  python code/ch02/run_all.py
Scripts: fees_waterfalls, carry_options, simulated_funds, hedge_fund_fees, promote_pacing, exercises.
Writes  figures/ch02/*.png, code/ch02/out/*.json, code/ch02/out/numbers.json, chapters/ch02-numbers.tex
"""
import importlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numbers_ch02 as R  # noqa: E402

SCRIPTS = ["fees_waterfalls", "carry_options", "simulated_funds", "hedge_fund_fees", "promote_pacing", "exercises"]


def main():
    for s in SCRIPTS:
        importlib.import_module(s).main()
        print(f"{s}: done ({len(R.N)} numbers so far)")
    (HERE / "out" / "numbers.json").write_text(json.dumps(dict(N=R.N, RAW=R.RAW), indent=1))
    lines = ["% Generated by code/ch02/run_all.py. Do not edit by hand."]
    lines += [f"\\newcommand{{\\{k}}}{{{R.N[k]}}}" for k in sorted(R.N)]
    (R.ROOT / "chapters" / "ch02-numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(R.N)} numbers, figures in {R.ROOT / 'figures' / 'ch02'}")


if __name__ == "__main__":
    main()
