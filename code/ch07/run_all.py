"""Regenerate every number and figure in Chapter 7 by running each of the chapter's scripts.

Usage:  python code/ch07/run_all.py
Scripts: frontier, capm_factors, alpha_tests, smoothing_beta, option_alpha, attribution,
black_litterman, allocation, case_oos, exercises. Each draws from its own random stream
(numbers_ch07.rng_for), so a script run alone reproduces exactly the numbers it contributes here.
Writes  figures/ch07/*.png, code/ch07/out/*.json, code/ch07/out/numbers.json, chapters/ch07-numbers.tex
"""
import importlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numbers_ch07 as R  # noqa: E402

SCRIPTS = ["frontier", "capm_factors", "alpha_tests", "smoothing_beta", "option_alpha", "attribution",
           "black_litterman", "allocation", "case_oos", "exercises"]


def main(only=None):
    for s in (only or SCRIPTS):
        importlib.import_module(s).main()
        print(f"{s}: done ({len(R.N)} numbers so far)", flush=True)
    (HERE / "out" / "numbers.json").write_text(json.dumps(dict(N=R.N, RAW=R.RAW), indent=1))
    lines = ["% Generated by code/ch07/run_all.py. Do not edit by hand."]
    for k in sorted(R.N):
        assert k.isalpha(), k
        lines.append(f"\\newcommand{{\\{k}}}{{{R.N[k]}}}")
    (R.ROOT / "chapters" / "ch07-numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(R.N)} numbers, figures in {R.ROOT / 'figures' / 'ch07'}")


if __name__ == "__main__":
    main(sys.argv[1:] or None)
