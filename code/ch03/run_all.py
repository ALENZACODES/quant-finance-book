"""Regenerate every number and figure in Chapter 3 by running each of the chapter's scripts.

Usage:  python code/ch03/run_all.py
Scripts: random_walks, brownian_qv, ito_integral, sde_models, martingales_girsanov, feynman_kac,
canadian_rates, exercises. Each draws from its own random stream (numbers_ch03.rng_for), so a script run alone
reproduces exactly the numbers it contributes here.
Writes  figures/ch03/*.png, code/ch03/out/*.json, code/ch03/out/numbers.json, chapters/ch03-numbers.tex
"""
import importlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numbers_ch03 as R  # noqa: E402

SCRIPTS = ["random_walks", "brownian_qv", "ito_integral", "sde_models", "martingales_girsanov", "feynman_kac",
           "canadian_rates", "exercises"]


def main():
    for s in SCRIPTS:
        importlib.import_module(s).main()
        print(f"{s}: done ({len(R.N)} numbers so far)")
    (HERE / "out" / "numbers.json").write_text(json.dumps(dict(N=R.N, RAW=R.RAW), indent=1))
    lines = ["% Generated by code/ch03/run_all.py. Do not edit by hand."]
    for k in sorted(R.N):
        assert k.isalpha(), k
        lines.append(f"\\newcommand{{\\{k}}}{{{R.N[k]}}}")
    (R.ROOT / "chapters" / "ch03-numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(R.N)} numbers, figures in {R.ROOT / 'figures' / 'ch03'}")


if __name__ == "__main__":
    main()
