"""Regenerate every number and figure in Chapter 5 by running each of the chapter's scripts.

Usage:  python code/ch05/run_all.py
Scripts: closed_form, dividends_black, monte_carlo, finite_diff, implied_vol, hedging_pnl,
case_fx_hedge, exercises. Each draws from its own random stream (numbers_ch05.rng_for), so a script
run alone reproduces exactly the numbers it contributes here.
Writes  figures/ch05/*.png, code/ch05/out/*.json, code/ch05/out/numbers.json, chapters/ch05-numbers.tex
"""
import importlib, json, sys, warnings
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numbers_ch05 as R  # noqa: E402

SCRIPTS = ["closed_form", "dividends_black", "monte_carlo", "finite_diff", "implied_vol", "hedging_pnl",
           "case_fx_hedge", "exercises"]


def main(only=None):
    warnings.filterwarnings("ignore", message=".*roundoff error.*")
    for s in SCRIPTS:
        importlib.import_module(s).main()
        print(f"{s}: done ({len(R.N)} numbers so far)", flush=True)
    (HERE / "out" / "numbers.json").write_text(json.dumps(dict(N=R.N, RAW=R.RAW), indent=1))
    lines = ["% Generated by code/ch05/run_all.py. Do not edit by hand."]
    for k in sorted(R.N):
        assert k.isalpha(), k
        lines.append(f"\\newcommand{{\\{k}}}{{{R.N[k]}}}")
    (R.ROOT / "chapters" / "ch05-numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(R.N)} numbers, figures in {R.ROOT / 'figures' / 'ch05'}")


if __name__ == "__main__":
    main()
