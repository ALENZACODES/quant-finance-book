"""Regenerate every number and figure in Chapter 6 by running each of the chapter's scripts.

Usage:  python code/ch06/run_all.py
Scripts: bonds_duration, short_rates, swaps_caps, merton_model, hazard_cds, copula_tranches,
private_credit, direct_lending, case_refinance, exercises. Each draws from its own random stream
(numbers_ch06.rng_for), so a script run alone reproduces exactly the numbers it contributes here.
Writes  figures/ch06/*.png, code/ch06/out/*.json, code/ch06/out/numbers.json, chapters/ch06-numbers.tex
"""
import importlib, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numbers_ch06 as R  # noqa: E402

SCRIPTS = ["bonds_duration", "short_rates", "swaps_caps", "merton_model", "hazard_cds", "copula_tranches",
           "private_credit", "direct_lending", "case_refinance", "exercises"]


def main():
    for s in SCRIPTS:
        importlib.import_module(s).main()
        print(f"{s}: done ({len(R.N)} numbers so far)", flush=True)
    (HERE / "out" / "numbers.json").write_text(json.dumps(dict(N=R.N, RAW=R.RAW), indent=1))
    lines = ["% Generated by code/ch06/run_all.py. Do not edit by hand."]
    for k in sorted(R.N):
        assert k.isalpha(), k
        lines.append(f"\\newcommand{{\\{k}}}{{{R.N[k]}}}")
    (R.ROOT / "chapters" / "ch06-numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(R.N)} numbers, figures in {R.ROOT / 'figures' / 'ch06'}")


if __name__ == "__main__":
    main()
