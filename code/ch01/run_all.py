"""Regenerate every number and figure in Chapter 1 by running each of the chapter's scripts.

Usage:  python code/ch01/run_all.py
Scripts: rates_returns, irr_multiples, distributions, smoothing_normality, goc_case. They share one
random generator (seed 101) in this order, so the numbers in the text are reproducible.
Writes  figures/ch01/*.png, code/ch01/out/*.json, code/ch01/out/numbers.json, chapters/ch01-numbers.tex
"""
import importlib, json, sys
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numbers_ch01 as R  # noqa: E402

SCRIPTS = ["rates_returns", "irr_multiples", "distributions", "smoothing_normality", "goc_case"]


def main():
    rng = np.random.default_rng(R.SEED)
    for s in SCRIPTS:
        importlib.import_module(s).main(rng)
        print(f"{s}: done ({len(R.N)} numbers so far)")
    (HERE / "out" / "numbers.json").write_text(json.dumps(dict(N=R.N, RAW=R.RAW), indent=1, default=str))
    lines = ["% Generated by code/ch01/run_all.py. Do not edit by hand."]
    for k in sorted(R.N):
        assert k.isalpha(), k
        lines.append(f"\\newcommand{{\\{k}}}{{{R.N[k]}}}")
    (R.ROOT / "chapters" / "ch01-numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(R.N)} numbers, figures in {R.ROOT / 'figures' / 'ch01'}")


if __name__ == "__main__":
    main()
